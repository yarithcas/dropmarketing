import { chromium } from "@playwright/test";

const out = process.argv[2];
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await ctx.addCookies([{ name: "th_lang", value: "fr", url: "http://localhost:3204" }]);
const page = await ctx.newPage();
await page.goto("http://localhost:3204/app/ads");
await page.getByTestId("ad-card").first().waitFor();
await page.getByTestId("active-advertiser-badge").first().hover();
await page.screenshot({ path: `${out}/ads.png` });
await page.goto("http://localhost:3204/app/ads?minActiveAds=50");
await page.getByTestId("show-all-ads").waitFor();
await page.screenshot({ path: `${out}/ads-empty.png` });
await page.goto("http://localhost:3204/app/products/smart-jump-rope-with-counter");
await page.getByTestId("product-related-ads").scrollIntoViewIfNeeded();
await page.getByTestId("product-related-ads").screenshot({ path: `${out}/product.png` });
await page.goto("http://localhost:3204/app/search?q=corner");
await page.getByTestId("active-advertiser-flag").first().waitFor();
await page.screenshot({ path: `${out}/search.png` });
const mobile = await browser.newContext({ viewport: { width: 390, height: 844 } });
await mobile.addCookies([{ name: "th_lang", value: "fr", url: "http://localhost:3204" }]);
const m = await mobile.newPage();
await m.goto("http://localhost:3204/app/ads");
await m.getByTestId("ad-card").first().waitFor();
await m.screenshot({ path: `${out}/ads-mobile.png` });
await browser.close();
