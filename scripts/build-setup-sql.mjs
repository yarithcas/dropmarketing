// Concatenates supabase/migrations/*.sql (in order) into supabase/setup.sql, for a one-paste setup in the
// Supabase SQL editor. Run `node scripts/build-setup-sql.mjs` after adding a migration (a test checks it).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const header = `-- TrendHunter: every migration of ${dir}, in order (${files.join(", ")}).\n-- Generated by scripts/build-setup-sql.mjs — do not edit. Paste it once in the Supabase SQL editor and Run.\n`;
const body = files.map((f) => `\n-- ═══ ${f} ═══\n${readFileSync(join(dir, f), "utf8").trimEnd()}\n`).join("");
writeFileSync("supabase/setup.sql", header + body);
console.log(`supabase/setup.sql: ${files.length} migrations`);
